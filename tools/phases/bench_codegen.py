#!/usr/bin/env python
"""bench_codegen — turn the measured day-wise benchmark into `src/benchmark.py`.

`docs/boey_bench.json` is the evidence; `src/benchmark.py` is what the agent steers with.
The bundle is a single file built from `src/`, so the targets have to be literals.

The module is not a report -- it is a CONTROLLER. `pressure(metric, day, ours)` returns how
far behind the reference we are on that metric today, as a multiplier >= 1 that the crew's
job valuation applies. That is what makes the machine steer toward his surface day by day
instead of being judged against it after the fact.

Usage
-----
  PYTHONPATH=. python -m tools.phases.boey_bench --all --workers 8   # refresh evidence
  PYTHONPATH=. python -m tools.phases.bench_codegen                  # refresh src/benchmark.py
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

HEADER = '''"""benchmark — the reference's day-wise surface, as the target the crew steers toward.

GENERATED by `tools/phases/bench_codegen.py` from `docs/boey_bench.json`; do not edit by
hand. Evidence: {games} games, d{d0}-d{d1}. Values are p25/p50/p75 ACROSS GAMES per day.

This is a control loop, not a report. `pressure(metric, day, ours)` says how far behind we
are, and the crew multiplies a job's dollar value by it, so a day that drifts off his
surface pushes harder on the work that closes it.

MEASURED facts behind the targets:
  * `plants_died` and `weeds_max` are **0/0/0 for him every day to d19**, and only rise
    after d24 -- his deliberate wind-down. The target is therefore ~0 until d20 and rising
    afterwards is OPTIMAL, not a defect.
  * His mid-game `idle_share_pct` is 1.3; ours is 0.0. Idleness is not our defect.
  * `max_shed_total` rises smoothly 7 -> 46 (d10) -> 92 (d24); hitting the 100 cap means
    discards.
"""
from __future__ import annotations

# metric -> day -> (p25, p50, p75)
TARGETS = {targets}

# What each steering signal watches, and the metric it is judged against.
SIGNALS = {signals}


def band(metric, day):
    """(p25, p50, p75) he sits in on `day`, or None."""
    t = TARGETS.get(metric)
    if not t:
        return None
    if day in t:
        return t[day]
    earlier = [d for d in t if d <= day]
    return t[max(earlier)] if earlier else t[min(t)]


def target(metric, day):
    """His median for `metric` on `day` -- the number to steer to."""
    b = band(metric, day)
    return None if b is None else b[1]


def gap(metric, day, ours):
    """ours - target. Positive = worse for a defect metric, better for money/production."""
    t = target(metric, day)
    return None if t is None else float(ours) - float(t)


def pressure(metric, day, ours, slope=1.0, cap=4.0, width=None):
    """How hard to push on `metric` today: 1.0 at or better than target, rising with the gap.

    The reference's own spread sets the scale: one p75-p25 band width off target adds
    `slope` to the multiplier. For a metric whose target is 0 and whose spread is therefore
    0 -- `plants_died`, `weeds_max`, `animals_escaped` -- the caller must pass `width`,
    scaled to the farm (e.g. 5 % of the planted tiles), or the multiplier saturates on the
    first unit and stops carrying information.
    """
    b = band(metric, day)
    if b is None or ours is None:
        return 1.0
    lo, mid, hi = b
    excess = float(ours) - float(mid)
    if excess <= 0:
        return 1.0
    w = width if width else ((hi - lo) or max(1.0, abs(mid) * 0.25))
    return min(cap, 1.0 + slope * (excess / max(1e-9, w)))
'''
TARGET_METRICS = ("plants_died", "weeds_max", "animals_escaped", "discarded_units",
                  "max_shed_total", "end_shed_total", "idle_share_pct", "unit_turns",
                  "end_money", "premium_below_base_frac", "feed_surplus",
                  "plants_watered", "plants_fertilized", "animals_fed", "animals_cared")
SIGNALS = {
    "weeds": ("weeds_max", "DIG"),
    "plants_at_risk": ("plants_died", "WATER"),
    "animals_at_risk": ("animals_escaped", "FEED"),
    "shed_pressure": ("max_shed_total", "DROP"),
    "cash": ("end_money", "SELL"),
}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default="docs/boey_bench.json")
    ap.add_argument("--out", default="src/benchmark.py")
    a = ap.parse_args(argv)
    b = json.load(open(a.json))
    days = sorted(int(d) for d in b)
    T = {}
    for m in TARGET_METRICS:
        rows = {}
        for d in days:
            c = b.get(str(d), {}).get(m)
            if c and c.get("p50") is not None:
                rows[d] = (round(c["p25"] or 0, 1), round(c["p50"], 1),
                           round(c["p75"] or 0, 1))
        if rows:
            T[m] = rows
    body = HEADER.replace("{targets}", repr(T)).replace("{signals}", repr(SIGNALS))
    body = body.replace("{games}", str(len(days) and next(iter(b.values())) and "measured"))
    body = body.replace("{d0}", str(days[0]) if days else "0")
    body = body.replace("{d1}", str(days[-1]) if days else "0")
    body = body.replace('Evidence: measured games', 'Evidence: measured games')
    Path(a.out).write_text(body)
    print(f"wrote {a.out} ({len(body)} bytes); metrics {len(T)}, days {len(days)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
